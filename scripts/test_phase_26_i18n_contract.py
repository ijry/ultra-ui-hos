#!/usr/bin/env python3
"""Static contracts for the Phase 26 i18n pass."""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CORE = ROOT / "ultra-ui/src/main/ets/core"
COMPONENTS = ROOT / "ultra-ui/src/main/ets/components"
INTERNAL = ROOT / "ultra-ui/src/main/ets/internal"
SNAPSHOT = ROOT / "tools/upstream/uview-plus-locales"
GENERATOR = ROOT / "tools/generate_uplocale_catalog.py"
DEMO = ROOT / "sample/entry/src/main/ets/demos/I18nDemo.ets"
CATALOG = ROOT / "sample/entry/src/main/ets/catalog/SampleCatalog.ets"
PAGE = ROOT / "sample/entry/src/main/ets/pages/SamplePage.ets"
INDEX = ROOT / "ultra-ui/Index.ets"
README = ROOT / "README.md"
NOTE = ROOT / "docs/compatibility/phase-26.md"

FORBIDDEN = (
    "WebView", "webview", "FastView", ".xyfv", "@kit.NetworkKit", "http://",
    "https://", "JSON.parse", "fetch(", "axios", "setClipboardData",
    "openSystemSettings", "plus.runtime.quit", "navigateTo", "RichText",
)

# upstream locale files that must be pinned under tools/upstream
LOCALE_FILES = ("zh-Hans", "zh-Hant", "en", "es", "fr", "de", "ko", "ja", "ru", "th")

# component -> (i18n key, upstream props.js field) pairs the defaults must read
WIRED_DEFAULTS = {
    "UPActionSheet": (("cancelText", "up.common.cancel"),),
    "UPModal": (("confirmText", "up.common.confirm"), ("cancelText", "up.common.cancel"),
                ("asyncCloseTip", "up.common.inOperation")),
    "UPPicker": (("cancelText", "up.common.cancel"), ("confirmText", "up.common.confirm")),
    "UPKeyboard": (("confirmText", "up.common.confirm"), ("cancelText", "up.common.cancel")),
    "UPSearch": (("placeholder", "up.search.placeholder"), ("actionText", "up.common.search")),
    "UPReadMore": (("closeText", "up.readMore.expand"), ("openText", "up.readMore.fold")),
    "UPLoadmore": (("loadingText", "up.common.loading2"), ("loadmoreText", "up.loadmoe.loadmore"),
                   ("nomoreText", "up.loadmoe.nomore")),
    "UPSection": (("subTitle", "up.common.more"),),
    "UPLoadingPage": (("loadingText", "up.common.loading2"),),
    "UPCode": (("startText", "up.code.send"), ("changeText", "up.code.resendAfter"),
               ("endText", "up.code.resend")),
    "UPNoNetwork": (("tips", "up.noNetwork.text"), ("retryText", "up.common.retry")),
    "UPToolbar": (("cancelText", "up.common.cancel"), ("confirmText", "up.common.confirm")),
    "UPCascader": (("title", "up.common.pleaseChoose"),),
    "UPGoodsSku": (("confirmText", "up.common.confirm"),),
}

# component -> keys read through an exported constant or a render-time fallback
WIRED_LOOKUPS = {
    "UPCalendar": ("up.calendar.disabled",),
    "UPCityLocate": ("up.cityLocate.locateCity", "up.cityLocate.locating", "up.cityLocate.fail"),
    "UPPagination": ("up.pagination.previous", "up.pagination.next"),
    "UPGoodsSku": ("up.goodsSku.buyAmount",),
}

# internal modules whose copy now reads the locale pack
WIRED_INTERNAL = {
    "UPCropperGeometry.ets": ("up.common.re-select", "up.common.close", "up.common.rotate",
                              "up.common.preview", "up.common.confirm", "up.cropper.emptyWidhtOrHeight"),
    "UPNovelLayout.ets": ("up.common.retry",),
    "UPTriggerInput.ets": ("up.common.pleaseChoose",),
}

# UPI18n runtime surface mirroring the upstream i18n module
RUNTIME_MEMBERS = ("locale", "setLocale", "hasLocale", "locales", "keys",
                   "registerLocale", "clearLocale", "t", "translate")


def read(path: Path) -> str:
    assert path.is_file(), f"missing file: {path.relative_to(ROOT)}"
    return path.read_text(encoding="utf-8")


def upstream_pack(stem: str) -> dict[str, str]:
    text = read(SNAPSHOT / f"{stem}.js")
    entries: dict[str, str] = {}
    for match in re.finditer(r'"(up\.[^"]+)"\s*:\s*"((?:[^"\\]|\\.)*)"', text):
        entries[match.group(1)] = json.loads(f'"{match.group(2)}"')
    return entries


def main() -> None:
    assert GENERATOR.is_file(), "the locale catalog generator must be checked in"
    for stem in LOCALE_FILES:
        assert (SNAPSHOT / f"{stem}.js").is_file(), f"pinned locale snapshot missing: {stem}.js"

    catalog = read(INTERNAL / "UPLocaleCatalog.ets")
    runtime = read(CORE / "UPI18n.ets")
    for source, name in ((catalog, "UPLocaleCatalog.ets"), (runtime, "UPI18n.ets")):
        for token in FORBIDDEN:
            assert token not in source, f"{name} contains forbidden boundary {token}"
        for banned in ("Record<", ": any", ": unknown", "async ", "await ", "Promise<"):
            assert banned not in source, f"{name} must not use {banned.strip()}"

    assert "Generated by tools/generate_uplocale_catalog.py" in catalog, (
        "UPLocaleCatalog must stay generated, not hand-edited"
    )

    # every pinned key/value pair must appear in the generated catalog
    reference = upstream_pack("zh-Hans")
    assert len(reference) >= 80, f"expected at least 80 upstream keys, found {len(reference)}"
    for tag in LOCALE_FILES:
        entries = upstream_pack(tag)
        assert set(entries.keys()) == set(reference.keys()), f"{tag} key set diverges from zh-Hans"
        assert f"['{tag}', new Map<string, string>([" in catalog, f"catalog is missing the {tag} pack"
    for key, value in reference.items():
        assert f"['{key}', '{value}']" in catalog, f"catalog is missing zh-Hans copy for {key}"
    assert f"KEY_COUNT: number = {len(reference)}" in catalog, "catalog must expose the key count"

    for member in RUNTIME_MEMBERS:
        assert re.search(rf"static {member}\(", runtime), f"UPI18n is missing {member}()"
    assert "UP_DEFAULT_LOCALE: string = 'zh-Hans'" in runtime, "the default locale must stay zh-Hans"
    assert "upWeekText" in runtime, "UPI18n must expose the weekText helper"
    # the platform locale is not read: uni.getLocale has no ArkTS twin in this HAR
    runtime_code = "\n".join(line for line in runtime.split("\n")
                             if not line.strip().startswith(("*", "/*", "//")))
    for probe in ("uni.getLocale", "uni.onLocaleChange", "i18n.getSystemLanguage",
                  "@ohos.i18n", "@kit.LocalizationKit"):
        assert probe not in runtime_code, f"UPI18n must not reach for the platform locale API {probe}"

    sources: dict[str, str] = {}
    wired = 0
    for name, pairs in WIRED_DEFAULTS.items():
        source = read(COMPONENTS / f"{name}.ets")
        sources[name] = source
        assert "from '../core/UPI18n'" in source, f"{name} must import the i18n runtime"
        for field, key in pairs:
            wired += 1
            assert re.search(rf"\b{field}\b[^=;\n]*=\s*UPI18n\.t\('{re.escape(key)}'\)", source), (
                f"{name}.{field} must default to UPI18n.t('{key}')"
            )

    for name, keys in WIRED_LOOKUPS.items():
        source = sources.get(name) or read(COMPONENTS / f"{name}.ets")
        sources[name] = source
        assert "from '../core/UPI18n'" in source, f"{name} must import the i18n runtime"
        for key in keys:
            wired += 1
            assert f"UPI18n.t('{key}')" in source, f"{name} must read {key}"

    for filename, keys in WIRED_INTERNAL.items():
        source = read(INTERNAL / filename)
        assert "from '../core/UPI18n'" in source, f"{filename} must import the i18n runtime"
        for key in keys:
            wired += 1
            assert f"UPI18n.t('{key}')" in source, f"{filename} must read {key}"

    # weekText defaults come from the shared helper, not seven inline literals
    for name in ("UPCalendar", "UPCalendarStrip"):
        assert "upWeekText()" in sources.get(name, read(COMPONENTS / f"{name}.ets")), (
            f"{name} must build weekText from upWeekText()"
        )

    # the validator gains a locale-aware table; this is a local addition, not upstream
    validator = read(CORE / "UPValidator.ets")
    assert "upZhHansValidateMessages" in validator and "upValidateMessagesFor" in validator, (
        "UPValidator must offer the locale-aware message tables"
    )
    controller = read(ROOT / "ultra-ui/src/main/ets/controllers/UPFormController.ets")
    assert "upValidateMessagesFor(UPI18n.locale())" in controller, (
        "UPFormController must pick messages by the active locale"
    )
    assert "setMessages(" in controller, "UPFormController must allow overriding the message table"

    index = read(INDEX)
    for symbol in ("UPI18n", "UPI18nParam", "UP_DEFAULT_LOCALE", "upText", "upWeekText",
                   "UPLocaleCatalog", "upZhHansValidateMessages", "upValidateMessagesFor"):
        assert symbol in index, f"public entry missing {symbol}"

    demo = read(DEMO)
    assert "@lingyun/ultra-ui-hos" in demo, "I18nDemo must import from the public HAR entry"
    assert not re.search(r"=>\s*this\.", demo), "I18nDemo must use explicit void block bodies"
    for token in ("UPI18n.locales()", "UPI18n.setLocale", "UPI18n.registerLocale", "UPI18n.clearLocale",
                  "UPI18n.translate", "upWeekText()", "upValidateMessagesFor", "up.calendar.daysExceed"):
        assert token in demo, f"I18nDemo does not demonstrate {token}"

    assert "'i18n'" in read(CATALOG), "sample catalog must register the i18n route"
    page = read(PAGE)
    assert "I18nDemo()" in page and "case 'i18n'" in page, "SamplePage must route the i18n demo"

    readme = read(README)
    note = read(NOTE)
    for phrase in ("阶段 26", "phase-26.md"):
        assert phrase in readme or phrase in note, f"Phase 26 documentation missing {phrase}"
    for phrase in (
        "API 24", "5.0.0(12)", "UPI18n", "UPLocaleCatalog", "registerLocale", "zh-Hans",
        "no-op", "设备验证", "skipped",
    ):
        assert phrase in note, f"phase-26 note missing {phrase}"

    print(f"phase 26 i18n contract: PASS ({len(LOCALE_FILES)} locales, {len(reference)} keys, "
          f"{wired} wired defaults)")


if __name__ == "__main__":
    main()
