#!/usr/bin/env python3
"""Static contracts for the Phase 27 light/dark theme pass."""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CORE = ROOT / "ultra-ui/src/main/ets/core"
COMPONENTS = ROOT / "ultra-ui/src/main/ets/components"
INTERNAL = ROOT / "ultra-ui/src/main/ets/internal"
SNAPSHOT = ROOT / "tools/upstream/uview-plus-theme.js"
GENERATOR = ROOT / "tools/generate_uptheme_tokens.py"
DEMO = ROOT / "sample/entry/src/main/ets/demos/ThemeDemo.ets"
CATALOG = ROOT / "sample/entry/src/main/ets/catalog/SampleCatalog.ets"
PAGE = ROOT / "sample/entry/src/main/ets/pages/SamplePage.ets"
INDEX = ROOT / "ultra-ui/Index.ets"
README = ROOT / "README.md"
NOTE = ROOT / "docs/compatibility/phase-27.md"

FORBIDDEN = (
    "WebView", "webview", "FastView", ".xyfv", "@kit.NetworkKit", "http://",
    "https://", "JSON.parse", "fetch(", "axios", "setClipboardData",
    "openSystemSettings", "plus.runtime.quit", "navigateTo", "RichText",
)

# token -> (light, dark) pairs pinned from the upstream colour maps
TOKEN_PAIRS = {
    "primary": ("#3c9cff", "#3c9cff"),
    "main-color": ("#303133", "#f5f5f5"),
    "content-color": ("#606266", "#d1d5db"),
    "tips-color": ("#909193", "#9ca3af"),
    "light-color": ("#c0c4cc", "#6b7280"),
    "border-color": ("#dadbde", "#3a3a3c"),
    "bg-color": ("#f3f4f6", "#1f1f1f"),
    "disabled-color": ("#c8c9cc", "#4b5563"),
    "card-bg-color": ("#ffffff", "#1c1c1e"),
    "navbar-bg-color": ("#ffffff", "#1c1c1e"),
    "hover-bg-color": ("#e7ebf0", "#343741"),
    "page-bg-color": ("#f3f4f6", "#1f1f1f"),
    "table2-header-bg-color": ("#f5f7fa", "#2a2d33"),
    "table2-zebra-bg-color": ("#fafafa", "#23262b"),
    "skeleton-bg-color": ("#f1f2f4", "#2f3135"),
    "gap-bg-color": ("#f3f4f6", "#111111"),
}

# UPThemeManager surface mirroring the upstream theme runtime
RUNTIME_MEMBERS = ("mode", "isDark", "preference", "snapshot", "setMode", "setPreference",
                   "systemModeChanged", "token", "tokenFor", "hasToken", "tokens",
                   "setOverrides", "clearOverrides", "theme", "addListener", "clearListeners")

# (attribute, token, light fallback) triples the components must now route through UPColor.token
WIRED_ATTRIBUTES = (
    ("backgroundColor", "card-bg-color", "#ffffff"),
    ("backgroundColor", "bg-color", "#f3f4f6"),
    ("fontColor", "main-color", "#303133"),
    ("fontColor", "content-color", "#606266"),
    ("fontColor", "tips-color", "#909399"),
    ("fontColor", "light-color", "#c0c4cc"),
    ("borderColor", "border-color", "#ebeef5"),
)


def read(path: Path) -> str:
    assert path.is_file(), f"missing file: {path.relative_to(ROOT)}"
    return path.read_text(encoding="utf-8")


def main() -> None:
    assert SNAPSHOT.is_file(), "the upstream theme.js snapshot must be pinned"
    assert GENERATOR.is_file(), "the theme token generator must be checked in"

    tokens = read(INTERNAL / "UPThemeTokens.ets")
    manager = read(CORE / "UPThemeManager.ets")
    colour = read(CORE / "UPColor.ets")
    for source, name in ((tokens, "UPThemeTokens.ets"), (manager, "UPThemeManager.ets"),
                         (colour, "UPColor.ets")):
        for token in FORBIDDEN:
            assert token not in source, f"{name} contains forbidden boundary {token}"
        for banned in ("Record<", ": any", ": unknown", "async ", "await ", "Promise<"):
            assert banned not in source, f"{name} must not use {banned.strip()}"

    assert "Generated by tools/generate_uptheme_tokens.py" in tokens, (
        "UPThemeTokens must stay generated, not hand-edited"
    )
    assert "COUNT: number = 42" in tokens, "the upstream table carries 42 tokens"

    # every pinned pair must land in the right mode table
    light_block = re.search(r"LIGHT: Map<string, string> = new Map<string, string>\(\[(.*?)\n  \]\);",
                            tokens, re.S)
    dark_block = re.search(r"DARK: Map<string, string> = new Map<string, string>\(\[(.*?)\n  \]\);",
                           tokens, re.S)
    assert light_block is not None and dark_block is not None, "both mode tables must exist"
    for token, (light_value, dark_value) in TOKEN_PAIRS.items():
        assert f"['{token}', '{light_value}']" in light_block.group(1), (
            f"light table is missing {token}={light_value}"
        )
        assert f"['{token}', '{dark_value}']" in dark_block.group(1), (
            f"dark table is missing {token}={dark_value}"
        )

    for member in RUNTIME_MEMBERS:
        assert re.search(rf"static {member}\(", manager), f"UPThemeManager is missing {member}()"
    assert "UP_DEFAULT_THEME_MODE: UPThemeMode = 'light'" in manager, "the default mode stays light"
    assert "upToken" in manager and "upModeValue" in manager, "the token helpers must be exported"
    # the platform theme is not probed: uni.getAppBaseInfo / onThemeChange have no ArkTS twin here
    manager_code = "\n".join(line for line in manager.split("\n")
                             if not line.strip().startswith(("*", "/*", "//")))
    for probe in ("uni.getAppBaseInfo", "uni.onThemeChange", "uni.getSystemInfoSync",
                  "@ohos.configuration", "getStorageSync"):
        assert probe not in manager_code, f"UPThemeManager must not probe {probe}"
    assert "systemMode: string" in manager, "the host must supply the system mode explicitly"

    # UPColor gained a token branch plus the explicit token() helper
    assert "static token(name: string, fallback: string): string" in colour, (
        "UPColor must expose token()"
    )
    assert "UPThemeManager.token(source, '')" in colour, (
        "UPColor.parse must fall through to the theme tokens"
    )
    # the four neutral names follow the active mode; brand colours stay mode-invariant
    assert "NEUTRAL_TOKENS" in colour and "static neutral(" in colour, (
        "UPColor must map the neutral colour names onto mode-aware tokens"
    )
    assert "static adaptive(light: string, token: string): string" in colour, (
        "UPColor must expose adaptive() for component-specific tokens"
    )
    assert "if (!UPThemeManager.isDark())" in colour, (
        "adaptive()/neutral() must keep the light value untouched"
    )
    for pair in ("['main', 'main-color']", "['content', 'content-color']",
                 "['tips', 'tips-color']", "['light', 'light-color']"):
        assert pair in colour, f"UPColor is missing the neutral mapping {pair}"
    assert "theme === UP_DEFAULT_THEME" in colour, (
        "an explicitly supplied theme must be respected verbatim"
    )

    # no component may read a neutral field off the default theme directly any more
    for directory in ("components", "internal"):
        for path in sorted((ROOT / "ultra-ui/src/main/ets" / directory).glob("*.ets")):
            source = path.read_text(encoding="utf-8")
            for field in ("main", "content", "tips", "light"):
                assert f"UP_DEFAULT_THEME.{field}" not in source, (
                    f"{path.stem} still reads UP_DEFAULT_THEME.{field}; use UPColor.neutral()"
                )

    # the component sweep actually routes the literals through the token table
    # 组件侧改用 UPColor.adaptive(浅色字面值, 令牌)：浅色照旧、暗色查令牌。
    wired = 0
    files: set[str] = set()
    for directory in ("components", "internal"):
        for path in sorted((ROOT / "ultra-ui/src/main/ets" / directory).glob("*.ets")):
            source = path.read_text(encoding="utf-8")
            for attribute, token, fallback in WIRED_ATTRIBUTES:
                pattern = f"{attribute}(UPColor.adaptive('{fallback}', '{token}'))"
                hits = source.count(pattern)
                if hits > 0:
                    wired += hits
                    files.add(path.stem)
            # no component may keep the old bare literal for a wired attribute
            for attribute, token, fallback in WIRED_ATTRIBUTES:
                assert f"{attribute}('{fallback}')" not in source, (
                    f"{path.stem} still hardcodes {attribute}('{fallback}')"
                )
    assert wired >= 90, f"expected at least 90 tokenised colour sites, found {wired}"
    assert len(files) >= 45, f"expected at least 45 tokenised files, found {len(files)}"

    # the informational colour audit ships alongside the theme pass
    audit = ROOT / "scripts/audit_theme_colors.py"
    assert audit.is_file(), "the theme colour audit script must be checked in"
    audit_src = audit.read_text(encoding="utf-8")
    assert "adaptive(" in audit_src and "neutral(" in audit_src, (
        "the audit must classify adaptive/neutral usage"
    )

    index = read(INDEX)
    for symbol in ("UPThemeManager", "UPThemeMode", "UPThemePreference", "UPThemeOverride",
                   "UPThemeSnapshot", "UP_DEFAULT_THEME_MODE", "upToken", "upModeValue",
                   "UPThemeTokens"):
        assert symbol in index, f"public entry missing {symbol}"

    demo = read(DEMO)
    assert "@lingyun/ultra-ui-hos" in demo, "ThemeDemo must import from the public HAR entry"
    assert not re.search(r"=>\s*this\.", demo), "ThemeDemo must use explicit void block bodies"
    for token in ("UPThemeManager.setMode", "UPThemeManager.setPreference", "UPThemeManager.tokenFor",
                  "UPThemeManager.setOverrides", "UPThemeManager.clearOverrides",
                  "UPThemeManager.addListener", "UPColor.token", "upModeValue"):
        assert token in demo, f"ThemeDemo does not demonstrate {token}"

    assert "'theme'" in read(CATALOG), "sample catalog must register the theme route"
    page = read(PAGE)
    assert "ThemeDemo()" in page and "case 'theme'" in page, "SamplePage must route the theme demo"

    readme = read(README)
    note = read(NOTE)
    for phrase in ("阶段 27", "phase-27.md"):
        assert phrase in readme or phrase in note, f"Phase 27 documentation missing {phrase}"
    for phrase in (
        "API 24", "5.0.0(12)", "UPThemeManager", "UPThemeTokens", "setPreference",
        "CSS", "no-op", "设备验证", "skipped",
    ):
        assert phrase in note, f"phase-27 note missing {phrase}"

    print(f"phase 27 theme contract: PASS (42 tokens, {wired} tokenised sites, {len(files)} files)")


if __name__ == "__main__":
    main()
