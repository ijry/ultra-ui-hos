#!/usr/bin/env python3
"""Generate the deterministic ArkTS UPIcon glyph catalog from pinned uview-plus icons.js."""

from __future__ import annotations

import argparse
import re
from pathlib import Path

ENTRY = re.compile(
    r"(?P<quote>['\"])(?P<name>uicon-[^'\"]+)(?P=quote)\s*:\s*"
    r"(?P<glyph_quote>['\"])(?P<glyph>\\u[0-9a-fA-F]{4})(?P=glyph_quote)",
)
PREFIX = "uicon-"


def parse_entries(source: Path) -> list[tuple[str, int]]:
    entries: list[tuple[str, int]] = []
    seen: set[str] = set()
    for match in ENTRY.finditer(source.read_text(encoding="utf-8")):
        upstream_name = match.group("name")
        name = upstream_name.removeprefix(PREFIX)
        if not name or name in seen:
            raise ValueError(f"Duplicate or malformed uview-plus icon name: {upstream_name}")
        seen.add(name)
        entries.append((name, int(match.group("glyph")[2:], 16)))
    if not entries:
        raise ValueError(f"No uview-plus icon entries found in {source}")
    return sorted(entries, key=lambda entry: entry[0])


def render(entries: list[tuple[str, int]], source: Path) -> str:
    lines = [
        "// Generated by tools/generate_upicon_catalog.py. Do not edit manually.",
        f"// Source snapshot: {source.as_posix()}",
        "",
        "/** Pinned uview-plus `uicon-*` glyphs rendered by the bundled font. */",
        "export class UPIconGlyphs {",
        "  private static readonly glyphs: Map<string, string> = new Map<string, string>([",
    ]
    lines.extend(f"    ['{name}', '\\u{code_point:04x}']," for name, code_point in entries)
    lines.extend(
        [
            "  ]);",
            "",
            f"  /** The {len(entries)} names from the pinned uview-plus `icons.js` catalog. */",
            "  static names(): string[] {",
            "    return Array.from(UPIconGlyphs.glyphs.keys());",
            "  }",
            "",
            "  /** Resolves a bare uview name or its single `uicon-` prefixed spelling. */",
            "  static codePoint(name: string): string | undefined {",
            "    const bareName = name.startsWith('uicon-') ? name.substring(6) : name;",
            "    return UPIconGlyphs.glyphs.get(bareName);",
            "  }",
            "}",
            "",
        ],
    )
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="Pinned uview-plus components/u-icon/icons.js")
    parser.add_argument("output", type=Path, help="Generated ArkTS output path")
    args = parser.parse_args()

    output = args.output
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(render(parse_entries(args.source), args.source), encoding="utf-8")


if __name__ == "__main__":
    main()
