#!/usr/bin/env python3
"""Generate the deterministic ArkTS UPLocaleCatalog from pinned uview-plus locale packs."""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ENTRY = re.compile(r'"(?P<key>up\.[^"]+)"\s*:\s*"(?P<value>(?:[^"\\]|\\.)*)"')

# upstream file stem -> ArkTS locale tag
LOCALES = (
    ('zh-Hans', 'zh-Hans'),
    ('zh-Hant', 'zh-Hant'),
    ('en', 'en'),
    ('es', 'es'),
    ('fr', 'fr'),
    ('de', 'de'),
    ('ko', 'ko'),
    ('ja', 'ja'),
    ('ru', 'ru'),
    ('th', 'th'),
)

HEADER = """// Generated by tools/generate_uplocale_catalog.py. Do not edit manually.
// Source snapshot: tools/upstream/uview-plus-locales/*.js

/**
 * 上游 `libs/i18n/locales` 的 ArkTS 快照：__LOCALES__ 种语言、每种 __KEYS__ 条文案。
 * Pinned snapshot of the upstream locale packs; keys and copy are byte-for-byte identical.
 */
export class UPLocaleCatalog {
"""


def parse_pack(path: Path) -> dict[str, str]:
    text = path.read_text(encoding='utf-8')
    entries: dict[str, str] = {}
    for match in ENTRY.finditer(text):
        key = match.group('key')
        if key in entries:
            raise ValueError(f'duplicate key {key} in {path.name}')
        entries[key] = json.loads(f'"{match.group("value")}"')
    if not entries:
        raise ValueError(f'no locale entries found in {path}')
    return entries


def escape(value: str) -> str:
    return value.replace('\\', '\\\\').replace("'", "\\'").replace('\n', '\\n')


def render(packs: dict[str, dict[str, str]], keys: list[str]) -> str:
    header = HEADER.replace('__LOCALES__', str(len(packs))).replace('__KEYS__', str(len(keys)))
    lines: list[str] = [header]
    lines.append('  private static readonly packs: Map<string, Map<string, string>> = '
                 'new Map<string, Map<string, string>>([')
    for tag, entries in packs.items():
        lines.append(f"    ['{tag}', new Map<string, string>([")
        for key in keys:
            lines.append(f"      ['{key}', '{escape(entries[key])}'],")
        lines.append('    ])],')
    lines.append('  ]);')
    lines.append('')
    lines.append('  /** 上游语言标签列表，顺序与 `locales/all.js` 一致。/ Locale tags in upstream order. */')
    tags = ', '.join(f"'{tag}'" for tag in packs)
    lines.append(f'  static readonly TAGS: Array<string> = [{tags}];')
    lines.append('')
    lines.append('  /** 文案键总数，用于契约校验。/ Key count, asserted by the contract script. */')
    lines.append(f'  static readonly KEY_COUNT: number = {len(keys)};')
    lines.append('')
    lines.append('  /** 某语言的完整文案表。/ The full table for one locale. */')
    lines.append('  static pack(tag: string): Map<string, string> | undefined {')
    lines.append('    return UPLocaleCatalog.packs.get(tag);')
    lines.append('  }')
    lines.append('')
    lines.append('  /** 是否内置该语言。/ Whether the tag ships with the library. */')
    lines.append('  static has(tag: string): boolean {')
    lines.append('    return UPLocaleCatalog.packs.has(tag);')
    lines.append('  }')
    lines.append('')
    lines.append('  /** 全部文案键，顺序与上游一致。/ Every key in upstream order. */')
    lines.append('  static keys(): Array<string> {')
    keys_literal = ',\n      '.join(f"'{key}'" for key in keys)
    lines.append('    return [')
    lines.append(f'      {keys_literal}')
    lines.append('    ];')
    lines.append('  }')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def main() -> None:
    parser = argparse.ArgumentParser()
    root = Path(__file__).resolve().parents[1]
    parser.add_argument('--source', type=Path, default=root / 'tools/upstream/uview-plus-locales')
    parser.add_argument('--output', type=Path,
                        default=root / 'ultra-ui/src/main/ets/internal/UPLocaleCatalog.ets')
    args = parser.parse_args()

    packs: dict[str, dict[str, str]] = {}
    for stem, tag in LOCALES:
        packs[tag] = parse_pack(args.source / f'{stem}.js')

    reference = list(packs['zh-Hans'].keys())
    for tag, entries in packs.items():
        if list(entries.keys()) != reference:
            raise ValueError(f'{tag} key order diverges from zh-Hans')

    args.output.write_text(render(packs, reference), encoding='utf-8')
    print(f'wrote {args.output.relative_to(root)}: {len(packs)} locales x {len(reference)} keys')


if __name__ == '__main__':
    main()
