#!/usr/bin/env python3
"""Generate the deterministic ArkTS UPThemeTokens table from the pinned uview-plus theme.js."""

from __future__ import annotations

import argparse
import re
from pathlib import Path

# `mainColor` -> `main-color`, matching the upstream LIGHT_THEME_TOKEN_FIELD_MAP direction.
FIELD_TOKEN = re.compile(r'([a-z0-9])([A-Z])')

# Tokens computed inside buildThemeCssVars() rather than declared in the colour maps.
# (token, light, dark) — the upstream fallbacks are literal, so they are pinned here.
DERIVED = (
    ('page-bg-color', 'bgColor', 'bgColor'),
)
LITERAL_DERIVED = (
    ('card-bg-color', '#ffffff', '#1c1c1e'),
    ('navbar-bg-color', '#ffffff', '#1c1c1e'),
    ('hover-bg-color', '#e7ebf0', '#343741'),
)

HEADER = """// Generated by tools/generate_uptheme_tokens.py. Do not edit manually.
// Source snapshot: tools/upstream/uview-plus-theme.js

/**
 * 上游 `libs/theme/theme.js` 的明暗主题令牌快照：__COUNT__ 个令牌 × 2 套取值。
 * Pinned snapshot of the upstream light/dark theme tokens. Upstream ships these as
 * CSS custom properties; ArkTS has no stylesheet layer, so they become a lookup table.
 */
export class UPThemeTokens {
"""


def token_of(field: str) -> str:
    return FIELD_TOKEN.sub(r'\1-\2', field).lower()


def parse_colour_map(text: str, name: str) -> dict[str, str]:
    block = re.search(rf'const {name} = Object\.freeze\(\{{(.*?)\n\}}\)', text, re.S)
    if block is None:
        raise ValueError(f'{name} not found in the pinned snapshot')
    entries: dict[str, str] = {}
    for match in re.finditer(r"(\w+):\s*'([^']+)'", block.group(1)):
        entries[token_of(match.group(1))] = match.group(2)
    if not entries:
        raise ValueError(f'{name} parsed empty')
    return entries


def parse_extra_vars(text: str, mode: str) -> dict[str, str]:
    block = re.search(rf"{mode}: Object\.freeze\(\{{(.*?)\n    \}}\)", text, re.S)
    if block is None:
        raise ValueError(f'DEFAULT_THEME_EXTRA_VARS.{mode} not found')
    entries: dict[str, str] = {}
    for match in re.finditer(r"'--up-([a-z0-9-]+)':\s*'([^']+)'", block.group(1)):
        entries[match.group(1)] = match.group(2)
    if not entries:
        raise ValueError(f'DEFAULT_THEME_EXTRA_VARS.{mode} parsed empty')
    return entries


def render(light: dict[str, str], dark: dict[str, str], tokens: list[str]) -> str:
    lines: list[str] = [HEADER.replace('__COUNT__', str(len(tokens)))]
    for mode, table in (('LIGHT', light), ('DARK', dark)):
        lines.append(f'  private static readonly {mode}: Map<string, string> = new Map<string, string>([')
        for token in tokens:
            lines.append(f"    ['{token}', '{table[token]}'],")
        lines.append('  ]);')
        lines.append('')
    lines.append('  /** 令牌名列表，按字母序。/ Token names in alphabetical order. */')
    literal = ',\n      '.join(f"'{token}'" for token in tokens)
    lines.append('  static names(): Array<string> {')
    lines.append('    return [')
    lines.append(f'      {literal}')
    lines.append('    ];')
    lines.append('  }')
    lines.append('')
    lines.append('  /** 令牌总数，用于契约校验。/ Token count, asserted by the contract script. */')
    lines.append(f'  static readonly COUNT: number = {len(tokens)};')
    lines.append('')
    lines.append('  /** 某模式下的令牌取值；未知令牌返回空串。/ Reads one token for a mode. */')
    lines.append('  static value(mode: string, token: string): string {')
    lines.append("    const table: Map<string, string> = mode === 'dark' ? UPThemeTokens.DARK : UPThemeTokens.LIGHT;")
    lines.append('    const found: string | undefined = table.get(token);')
    lines.append("    return found === undefined ? '' : found;")
    lines.append('  }')
    lines.append('')
    lines.append('  /** 是否存在该令牌。/ Whether the token exists. */')
    lines.append('  static has(token: string): boolean {')
    lines.append('    return UPThemeTokens.LIGHT.has(token);')
    lines.append('  }')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser()
    parser.add_argument('--source', type=Path, default=root / 'tools/upstream/uview-plus-theme.js')
    parser.add_argument('--output', type=Path,
                        default=root / 'ultra-ui/src/main/ets/internal/UPThemeTokens.ets')
    args = parser.parse_args()

    text = args.source.read_text(encoding='utf-8')
    light = parse_colour_map(text, 'DEFAULT_LIGHT_THEME_COLORS')
    dark = parse_colour_map(text, 'DEFAULT_DARK_THEME_COLORS')
    light.update(parse_extra_vars(text, 'light'))
    dark.update(parse_extra_vars(text, 'dark'))

    for token, light_field, dark_field in DERIVED:
        light[token] = light[token_of(light_field)]
        dark[token] = dark[token_of(dark_field)]
    for token, light_value, dark_value in LITERAL_DERIVED:
        light[token] = light_value
        dark[token] = dark_value

    missing = set(light.keys()) ^ set(dark.keys())
    if missing:
        raise ValueError(f'light/dark token sets diverge: {sorted(missing)}')

    tokens = sorted(light.keys())
    args.output.write_text(render(light, dark, tokens), encoding='utf-8')
    print(f'wrote {args.output.relative_to(root)}: {len(tokens)} tokens x 2 modes')


if __name__ == '__main__':
    main()
